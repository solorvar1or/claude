export const getCategory = (id: CategoryId) => categories.find((c) => c.id === id)!;
export const pageCategories = categories.filter((c) => c.page);
export const hubSections = categories.filter((c) => !c.page);
export const categoryUrl = (id: CategoryId) => {
  const c = getCategory(id);
  return c.page ? `/${c.id}/` : `/korpusnaya-mebel/#${c.id}`;
};

// Options for the "Что нужно?" step of forms.
export const formCategories = categories.filter((c) => c.id !== 'korpusnaya-mebel');
